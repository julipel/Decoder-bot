"""
Механизм оценки размера для `TokenBudgetPolicy` (Sprint 4, задача S4-06,
ADR-4.4) — эвристика, не реальный токенизатор.

`estimate_size()` — количество символов текста. Явно задокументированное
MVP-приближение: реальное число токенов, которое увидит модель/провайдер,
обычно МЕНЬШЕ (для смешанного ru/en-текста 1 токен ≈ 3-4 символа), а не
1:1 с этой оценкой — `PromptSettings.token_budget` (`shared/config.py`,
значение по умолчанию 12000) подобран заведомо консервативно относительно
типичного контекстного окна используемых моделей именно из-за этого
несовпадения (ADR-4.4). В `pyproject.toml` не добавлено никакой
зависимости-токенизатора (`tiktoken` и т.п.).

Изолирован в отдельной функции (не инлайнится в `TokenBudgetPolicy.
enforce()`, ADR-4.4/4.5) — единственное место, которое нужно заменить,
если в будущем потребуется реальный токенизатор конкретного провайдера;
`domain/prompt/policies.py::TokenBudgetPolicy` не потребует изменений —
она принимает `estimate_size` через конструктор как непрозрачный
`Callable[[str], int]` и ничего не знает о его реализации.
"""

from __future__ import annotations


def estimate_size(text: str) -> int:
    """Эвристическая оценка размера текста — количество символов (ADR-4.4), не реальных токенов модели."""
    return len(text)
